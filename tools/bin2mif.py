#!/usr/bin/env python3
"""bin2mif.py -- flat binary -> Quartus .mif memory image (32-bit words, little endian).

Used for the SSP factory ROM (D-38): ssp/rtl/ssp_sdp_ram.vhd takes it as the
altsyncram init_file of the MROM instance.  Runs of identical words are emitted
as address ranges, so the mostly-empty dictionary window costs a handful of
lines and a recommit is a small diff.

usage: bin2mif.py IN.bin OUT.mif WORDS
       bin2mif.py --check IN.bin FILE.mif WORDS     (exit 1 if FILE.mif != IN.bin)
  WORDS  depth in 32-bit words (16384 = the 64 KiB MROM)
"""
import re
import sys


def words(path, depth):
    data = bytearray(open(path, "rb").read())
    if len(data) % 4:
        data += b"\x00" * (4 - len(data) % 4)
    if len(data) > depth * 4:
        sys.exit("bin2mif: image %d bytes exceeds %d words" % (len(data), depth))
    data += b"\x00" * (depth * 4 - len(data))
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def render(w, src):
    out = ["-- generated by tools/bin2mif.py from %s -- DO NOT EDIT" % src,
           "DEPTH = %d;" % len(w), "WIDTH = 32;",
           "ADDRESS_RADIX = HEX;", "DATA_RADIX = HEX;", "CONTENT", "BEGIN"]
    i = 0
    while i < len(w):
        j = i
        while j + 1 < len(w) and w[j + 1] == w[i]:
            j += 1
        if j > i + 1:
            out.append("[%04X..%04X] : %08X;" % (i, j, w[i]))
        else:
            for k in range(i, j + 1):
                out.append("%04X : %08X;" % (k, w[i]))
        i = j + 1
    out.append("END;")
    return "\n".join(out) + "\n"


def parse(path, depth):
    w = [None] * depth
    body = False
    for line in open(path):
        line = line.split("--")[0].strip()
        if line == "BEGIN":
            body = True
        elif line == "END;":
            break
        elif body and line:
            m = re.match(r"\[([0-9A-Fa-f]+)\.\.([0-9A-Fa-f]+)\]\s*:\s*([0-9A-Fa-f]+);", line)
            if m:
                a, b, v = int(m.group(1), 16), int(m.group(2), 16), int(m.group(3), 16)
                for k in range(a, b + 1):
                    w[k] = v
                continue
            m = re.match(r"([0-9A-Fa-f]+)\s*:\s*([0-9A-Fa-f]+);", line)
            if not m:
                sys.exit("bin2mif: cannot parse '%s'" % line)
            w[int(m.group(1), 16)] = int(m.group(2), 16)
    return w


def main():
    a = sys.argv[1:]
    if len(a) == 4 and a[0] == "--check":
        want = words(a[1], int(a[3], 0))
        have = parse(a[2], int(a[3], 0))
        bad = [i for i in range(len(want)) if have[i] != want[i]]
        if bad:
            print("bin2mif: %s differs from %s at %d words (first: word %04X)" %
                  (a[2], a[1], len(bad), bad[0]))
            sys.exit(1)
        print("bin2mif: %s matches %s (%d words)" % (a[2], a[1], len(want)))
        return
    if len(a) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    w = words(a[0], int(a[2], 0))
    with open(a[1], "w", newline="\n") as f:
        f.write(render(w, a[0]))
    print("bin2mif: %s -> %s (%d words)" % (a[0], a[1], len(w)))


main()
