#!/usr/bin/env python3
"""bin2hex.py -- flat binary -> $readmemh word-image for simulation ROMs.

Emits one 32-bit little-endian word per line (8 hex digits), with an
'@xxxxxxxx' word-index start directive, padded to a fixed size so the
target array is fully initialised (no x in simulation; matches the
zero-filled "erased" assumption of the Mecrisp port, D-32).

usage: bin2hex.py IN.bin OUT.hex PADTO [BASE]
  PADTO  decimal or 0x byte count to pad the image to (ROM size)
  BASE   byte address the image loads at (default 0; word index = addr/4)
"""
import sys


def main():
    if len(sys.argv) < 4:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    src, dst = sys.argv[1], sys.argv[2]
    padto = int(sys.argv[3], 0)
    base = int(sys.argv[4], 0) if len(sys.argv) > 4 else 0

    data = bytearray(open(src, "rb").read())
    if len(data) % 4:
        data += b"\x00" * (4 - len(data) % 4)
    if padto and len(data) > padto:
        print("bin2hex: image %d bytes exceeds PADTO %d" % (len(data), padto),
              file=sys.stderr)
        sys.exit(1)
    if padto and len(data) < padto:
        data += b"\x00" * (padto - len(data))

    with open(dst, "w", newline="\n") as f:
        f.write("// generated by tools/bin2hex.py from %s -- DO NOT EDIT\n" % src)
        f.write("@%08X\n" % (base // 4))
        for i in range(0, len(data), 4):
            w = int.from_bytes(data[i:i + 4], "little")
            f.write("%08X\n" % w)
    print("bin2hex: %s -> %s (%d words @0x%08X)"
          % (src, dst, len(data) // 4, base))


if __name__ == "__main__":
    main()
