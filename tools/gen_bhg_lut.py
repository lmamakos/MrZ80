#!/usr/bin/env python3
"""gen_bhg_lut.py - regenerate Components/PSG/BHG_jt49_exp_q17.sv.

The vendored Components/YM2149/BHG_jt49_exp.sv builds its DAC table by
initialising a variable from other variables, which Quartus 17.0 rejects
(Error 10748).  This writes a drop-in module BHG_jt49_exp with the same
ports, holding the same tables (parsed from BHG_jt49_exp_lut.vh) as packed
constant localparams.  Run from anywhere:  tools/gen_bhg_lut.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'Components/YM2149/BHG_jt49_exp_lut.vh')
DST = os.path.join(ROOT, 'Components/PSG/BHG_jt49_exp_q17.sv')

HEADER = '''// BHG_jt49_exp_q17.sv - Quartus 17.0-compatible drop-in for the vendored
// Components/YM2149/BHG_jt49_exp.sv (module BHG_jt49_exp, same ports and
// parameter), which Quartus 17.0 rejects: its BHG_jt49_exp_lut.vh builds the
// table by initialising a variable from other variables (Error 10748,
// "expression in variable declaration assignment ... must be constant").
//
// GENERATED by tools/gen_bhg_lut.py from Components/YM2149/BHG_jt49_exp_lut.vh
// (BrianHG, BHG_jt49_exp_tablegen.v) -- do not edit; the tables are
// value-for-value identical, packed into constant localparams with entry 0 in
// the low 16 bits.  Behaviour is the same: one registered lookup of the 5-bit
// log level.  The vendored file stays unmodified and is simply not compiled.
//
// Original: BHG_jt49_exp.v v1.0, Aug 6, 2022 by Brian Guralnick
// (https://github.com/BrianHGinc).  "This code is free to use.  Just be fair
// and give credit where it is due."

module BHG_jt49_exp #(
    parameter [5:0] DAC_BITS = 8         // 8 thru 12 (10 ~ a real YM2149)
)(
    input                     clk,
    input      [4:0]          din,
    output reg [DAC_BITS-1:0] dout
);
'''

FOOTER = '''
    localparam [32*16-1:0] LUT = (DAC_BITS ==  8) ? LUT_8  :
                                 (DAC_BITS ==  9) ? LUT_9  :
                                 (DAC_BITS == 10) ? LUT_10 :
                                 (DAC_BITS == 11) ? LUT_11 : LUT_12;

    initial dout = 0;

    always @(posedge clk) dout <= LUT[din*16 +: DAC_BITS];

endmodule
'''

def main():
    src = open(SRC).read()
    tabs = {}
    for bits, body in re.findall(r"logic \[15:0\] dlut_(\d+)\s*\[0:31\]\s*=\s*'\{([^}]*)\}", src):
        vals = [int(v) for v in body.replace('\n', ' ').split(',')]
        assert len(vals) == 32, (bits, len(vals))
        tabs[int(bits)] = vals
    assert sorted(tabs) == [8, 9, 10, 11, 12], sorted(tabs)
    lines = [HEADER]
    for b in sorted(tabs):
        words = ', '.join("16'd%d" % v for v in reversed(tabs[b]))
        lines.append('    localparam [32*16-1:0] LUT_%d = {%s};' % (b, words))
    lines.append(FOOTER)
    with open(DST, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', os.path.relpath(DST, ROOT))

if __name__ == '__main__':
    main()
