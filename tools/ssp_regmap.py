#!/usr/bin/env python3
"""ssp_regmap.py -- SSP bridge register-map generator (D-29, R16).

Single source: ssp/regs/ssp_regs.csv
Emits:
  ssp/rtl/ssp_regs.vh         Verilog localparams (`SSP_REGS_VH include)
  ssp/rtl/ssp_regs_pkg.vhd    VHDL package        (D-33 VHDL side)
  ssp/fw/ssp-regs.fs          Mecrisp-Quintus constants (forth source)
  doc/SSP_REGS.md             authoritative Markdown table

Modes:
  python3 tools/ssp_regmap.py            generate (write only on change)
  python3 tools/ssp_regmap.py --check    verify outputs match CSV; exit 1
                                         on drift or bad CSV (R-45)

CSV columns: offset,name,access,reset,bits,fields,doc
  access in {R, RW, WO, RC, W1C, RCW}   (RCW = shared FW/engine, G-3)
  fields = "NAME=msb:lsb; NAME=bit"     (lsb omitted when == msb)
"""
import csv, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(ROOT, "ssp", "regs", "ssp_regs.csv")
OUTS = {
    "vh":  os.path.join(ROOT, "ssp", "rtl", "ssp_regs.vh"),
    "vhd": os.path.join(ROOT, "ssp", "rtl", "ssp_regs_pkg.vhd"),
    "fs":  os.path.join(ROOT, "ssp", "fw", "ssp-regs.fs"),
    "md":  os.path.join(ROOT, "doc", "SSP_REGS.md"),
}
BASE = 0x2000_0000
ACCESS = {"R", "RW", "WO", "RC", "W1C", "RCW"}


def die(msg):
    print("ssp_regmap: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def parse_fields(spec, width_hi):
    out = []
    for chunk in spec.split(";"):
        chunk = chunk.strip()
        if not chunk:
            continue
        m = re.fullmatch(r"([A-Z][A-Z0-9_]*)\s*=\s*(\d+)(?::(\d+))?", chunk)
        if not m:
            die("bad field spec %r" % chunk)
        name, hi = m.group(1), int(m.group(2))
        lo = int(m.group(3)) if m.group(3) else hi
        if lo > hi or hi > width_hi:
            die("field %s %d:%d outside register %d:0" % (name, hi, lo, width_hi))
        out.append((name, hi, lo))
    return out


def load():
    with open(CSV_PATH, newline="") as f:
        rows = [r for r in csv.DictReader(
            line for line in f if not line.lstrip().startswith("#"))]
    regs, seen = [], set()
    for r in rows:
        off = int(r["offset"], 16)
        if off % 4:
            die("offset %05x not word-aligned" % off)
        if off in seen:
            die("duplicate offset %05x (%s)" % (off, r["name"]))
        seen.add(off)
        if r["access"] not in ACCESS:
            die("%s: bad access %r" % (r["name"], r["access"]))
        bits = r["bits"].strip()
        hi = int(bits.split(":")[0]) if bits else 31
        regs.append({
            "off": off, "name": r["name"].strip(), "acc": r["access"],
            "reset": int(r["reset"], 16),
            "fields": parse_fields(r["fields"], hi),
            "doc": r["doc"].strip(),
        })
    return regs


GEN_TAG = "GENERATED by tools/ssp_regmap.py from ssp/regs/ssp_regs.csv -- DO NOT EDIT"


def emit_vh(regs):
    o = io.StringIO()
    o.write("// " + GEN_TAG + "\n`ifndef SSP_REGS_VH\n`define SSP_REGS_VH\n\n")
    o.write("`define SSP_BRIDGE_BASE 32'h%08X\n\n" % BASE)
    for r in regs:
        o.write("`define SSP_%-16s 32'h%08X  // %s reset 32'h%08X | %s\n"
                % (r["name"], BASE + r["off"], r["acc"], r["reset"], r["doc"]))
        for fn, hi, lo in r["fields"]:
            mask = ((1 << (hi - lo + 1)) - 1) << lo
            o.write("`define SSP_%s_%-14s 32'h%08X  // %d:%d\n"
                    % (r["name"], fn, mask, hi, lo))
        if r["fields"]:
            o.write("\n")
    o.write("`endif  // SSP_REGS_VH\n")
    return o.getvalue()


def emit_vhd(regs):
    o = io.StringIO()
    o.write("-- " + GEN_TAG + "\nlibrary ieee;\nuse ieee.std_logic_1164.all;\n"
            "use ieee.numeric_std.all;\n\npackage ssp_regs_pkg is\n\n")
    o.write('    constant SSP_BRIDGE_BASE : unsigned(31 downto 0) := x"%08X";\n\n'
            % BASE)
    for r in regs:
        o.write("    constant C_SSP_%-14s : natural := %d;  -- 0x%08X %s | %s\n"
                % (r["name"], BASE + r["off"], BASE + r["off"], r["acc"], r["doc"]))
        for fn, hi, lo in r["fields"]:
            o.write("    constant C_SSP_%s_%-12s : natural range 0 to 31 := %d;"
                    "  -- field %d:%d\n" % (r["name"], fn, hi, hi, lo))
        if r["fields"]:
            o.write("\n")
    o.write("end package ssp_regs_pkg;\n")
    return o.getvalue()


def emit_fs(regs):
    o = io.StringIO()
    o.write("\\ " + GEN_TAG + "\n\n")
    for r in regs:
        o.write("constant SSP_%s  $%08X  ( %s | %s )\n"
                % (r["name"], BASE + r["off"], r["acc"], r["doc"]))
        for fn, hi, lo in r["fields"]:
            mask = ((1 << (hi - lo + 1)) - 1) << lo
            o.write("constant SSP_%s_%s  $%08X  ( field %d:%d )\n"
                    % (r["name"], fn, mask, hi, lo))
        if r["fields"]:
            o.write("\n")
    return o.getvalue()


def emit_md(regs):
    o = io.StringIO()
    o.write("# SSP Bridge Register Map (generated)\n\n")
    o.write(">" + GEN_TAG + "\n>\n"
            "> Canonical input: `ssp/regs/ssp_regs.csv` (D-29). This view is\n"
            "> regenerated by `python3 tools/ssp_regmap.py`; consistency is\n"
            "> checked by `make -C sim regmap-check` (R-45). `SSP_DESIGN.md` "
            "SS6 is the\n> prose rationale; this table is the letter of the map.\n\n")
    o.write("Base `0x%08X`, word offsets, 4 KiB. Access: R, RW, WO, RC "
            "(read-clear),\nW1C, RCW (shared FW/engine, G-3).\n\n" % BASE)
    o.write("| Off | Reg | Acc | Reset | Fields (msb:lsb) | Description |\n")
    o.write("|----:|-----|-----|------:|------------------|-------------|\n")
    for r in regs:
        fields = "; ".join("%s %d:%d" % f for f in r["fields"])
        o.write("| 0x%03X | `%s` | %s | `%08X` | %s | %s |\n"
                % (r["off"], r["name"], r["acc"], r["reset"], fields, r["doc"]))
    return o.getvalue()


def maybe_write(path, content, check):
    old = None
    if os.path.exists(path):
        with open(path) as f:
            old = f.read()
    if old == content:
        return True
    if check:
        print("ssp_regmap: DRIFT: %s is not current" % os.path.relpath(path, ROOT),
              file=sys.stderr)
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(content)
    print("ssp_regmap: wrote %s" % os.path.relpath(path, ROOT))
    return True


def main():
    check = "--check" in sys.argv[1:]
    regs = load()
    emitters = {"vh": emit_vh, "vhd": emit_vhd, "fs": emit_fs, "md": emit_md}
    ok = all(maybe_write(OUTS[k], emitters[k](regs), check) for k in OUTS)
    n_fields = sum(len(r["fields"]) for r in regs)
    if check:
        print("ssp_regmap: check %s (%d regs, %d fields)"
              % ("OK" if ok else "FAILED", len(regs), n_fields))
        sys.exit(0 if ok else 1)
    print("ssp_regmap: generated %d regs, %d fields" % (len(regs), n_fields))


if __name__ == "__main__":
    main()
